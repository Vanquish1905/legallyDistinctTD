/**
 * Regenerates every texture under public/assets/art and rewrites src/data/artManifest.ts.
 * Sprites ship as SVG; map backgrounds and thumbnails are pre-rendered to JPEG (see lib/rasterize).
 * Run with `npm run art`. Map backgrounds are produced only when src/data/maps.ts exists.
 */
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { allSpriteAssets } from './catalog';
import type { ArtAsset } from './lib/asset';
import { rasterizeToJpeg, type RasterJob } from './lib/rasterize';
import { mapAssets } from './maps/render';
import { parseMaps } from './maps/types';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT_DIR = join(ROOT, 'public/assets/art');
const MANIFEST = join(ROOT, 'src/data/artManifest.ts');
const MAPS_FILE = join(ROOT, 'src/data/maps.ts');

async function loadMapAssets(): Promise<ArtAsset[]> {
  if (!existsSync(MAPS_FILE)) {
    process.stdout.write('art: src/data/maps.ts not found, skipping map backgrounds\n');
    return [];
  }
  const mod: unknown = await import(pathToFileURL(MAPS_FILE).href);
  const maps = parseMaps(mod);
  return maps.flatMap(mapAssets);
}

/** Map backgrounds and thumbnails are shipped as JPEG; everything else as SVG. */
const isRaster = (a: ArtAsset): boolean => a.dir === 'maps';
const fileName = (a: ArtAsset): string => `${a.key}.${isRaster(a) ? 'jpg' : 'svg'}`;

function manifestSource(assets: ArtAsset[]): string {
  const rows = assets
    .map(
      (a) =>
        `  { key: '${a.key}', path: 'assets/art/${a.dir}/${fileName(a)}', width: ${a.width}, height: ${a.height}, format: '${isRaster(a) ? 'image' : 'svg'}' },`,
    )
    .join('\n');
  return `/**
 * Generated by tools/art/generate.ts (npm run art). Do not edit by hand.
 * Every texture: Phaser key, URL relative to the page, pixel size and file format.
 * Load with \`loadArt(this.load, entries)\` from src/data/loadArt.ts.
 */

export interface ArtManifestEntry {
  key: string;
  path: string;
  width: number;
  height: number;
  /** 'svg' = rasterised by the browser at width×height, 'image' = pre-rendered JPEG. */
  format: 'svg' | 'image';
}

export const ART_MANIFEST: ArtManifestEntry[] = [
${rows}
];
`;
}

async function main(): Promise<void> {
  const assets = [...allSpriteAssets(), ...(await loadMapAssets())];
  const seen = new Set<string>();
  for (const a of assets) {
    if (seen.has(a.key)) throw new Error(`duplicate texture key ${a.key}`);
    seen.add(a.key);
  }
  rmSync(OUT_DIR, { recursive: true, force: true });
  const rasterJobs: RasterJob[] = [];
  for (const a of assets) {
    const dir = join(OUT_DIR, a.dir);
    mkdirSync(dir, { recursive: true });
    const svg = a.render();
    if (isRaster(a)) rasterJobs.push({ svg, width: a.width, height: a.height, outPath: join(dir, fileName(a)) });
    else writeFileSync(join(dir, fileName(a)), svg);
  }
  await rasterizeToJpeg(rasterJobs);
  writeFileSync(MANIFEST, manifestSource(assets));
  process.stdout.write(
    `art: wrote ${assets.length - rasterJobs.length} SVG textures, ${rasterJobs.length} JPEG map images and src/data/artManifest.ts\n`,
  );
}

await main();
